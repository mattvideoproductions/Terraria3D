        // Scans [from, to) for signature tile 0; [blockLo, blockHi) is the
        // mapped block, and the whole texture must fit inside it.
        void ScanSpan(u32 from, u32 to, u32 blockLo, u32 blockHi)
        {
            const u32 k0 = kSigTiles[0].words[0], k1 = kSigTiles[0].words[1];
            const u32 k2 = kSigTiles[0].words[2], k3 = kSigTiles[0].words[3];
            from = (from + 3) & ~3u;
            if (to < from + 16)
                return;
            for (u32 a = from; a + 16 <= to; a += 4)
            {
                if (W32(a) != k0 || W32(a + 4) != k1 || W32(a + 8) != k2 || W32(a + 12) != k3)
                    continue;
                const u32 base = a - kSigTiles[0].off;
                if (base < blockLo || base + kTexBytes > blockHi)
                    continue;
                if (VerifyCopy(base))
                    AddCopy(base);
            }
        }

